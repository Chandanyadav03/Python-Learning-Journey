## Rules for Defining a Variable Name

# Valid Variable Names
name = "Vipul"
age = 20
student_1 = "Rahul"
_marks = 85
one8 = 18
seven = 7

# Invalid Variable Names
# 1name = "Vipul"      # Starts with a digit
# my name = "Vipul"    # Contains space
# student@1 = "Rahul"  # Contains special character