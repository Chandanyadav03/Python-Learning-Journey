#  Arithmetic Operators +, -, *, /, %, **, //

a = 10
b= 10
c = a+b
print(c)

# Assignment Operators =, +=, -=, *=, /=, %=, **=, //=
a = 6
a +=3
print(a)

# Comparison Operators ==, !=, >, <, >=, <=

d = 10<5
print(d)

e = 10<=10
print(e)


# Logical Operators and, or, not
f = 1 or 5 
print(f)

g = 1 and 0
print(g)

h = not 1
print(h)